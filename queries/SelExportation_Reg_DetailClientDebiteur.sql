SELECT
  EXPORTATION_REG.*,
  EXPORTATION_IRR_DETAIL.*,
  CLIENT.*,
  DEBITEUR.*
FROM
  CLIENT
  INNER JOIN (
    (
      DEBITEUR
      INNER JOIN EXPORTATION_IRR_DETAIL ON DEBITEUR.Déb_Lot_EID_Id = EXPORTATION_IRR_DETAIL.EID_Id
    )
    INNER JOIN EXPORTATION_REG ON EXPORTATION_IRR_DETAIL.EID_Code = EXPORTATION_REG.EXPR_Id
  ) ON CLIENT.Cli_Code = DEBITEUR.Déb_Code_Client;
